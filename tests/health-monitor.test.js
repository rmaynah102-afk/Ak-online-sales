"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const vm=require("node:vm");
const source=fs.readFileSync("apk/ak-health-monitor.js","utf8");
const listeners={};
const window={addEventListener:(name,fn)=>{listeners[name]=fn}};
const document={addEventListener:()=>{},getElementById:()=>null,querySelector:()=>null};
const context={window,document,navigator:{onLine:true},URL,Blob,Date,console,setTimeout:()=>0,setInterval:()=>0};
vm.runInNewContext(source,context,{filename:"ak-health-monitor.js"});
const monitor=window.AKHealthMonitor;
assert.ok(monitor,"monitor API should be installed");
monitor.add("error","Test","failed password=hunter2 access_token=abc123 user@example.com");
const event=monitor.snapshot()[0];
assert.equal(event.level,"error");
assert.ok(!event.message.includes("hunter2"));
assert.ok(!event.message.includes("abc123"));
assert.ok(!event.message.includes("user@example.com"));
assert.ok(event.message.includes("[redacted]"));
assert.ok(event.message.includes("[email]"));
assert.equal(monitor.status().online,true);
assert.equal(monitor.issues().some(issue=>issue[0]==="error"),true);
const code=fs.readFileSync("apk/app.html","utf8");
assert.ok(code.includes('data-view="aiMonitor"'));
assert.ok(code.includes('id="aiMonitor"')===false,"monitor view is generated safely at runtime");
assert.ok(code.includes('if(id==="aiMonitor"'));
console.log("AK AI diagnostics: privacy redaction, issue detection and owner route checks passed");
